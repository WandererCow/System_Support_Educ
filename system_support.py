"""
Упрощенная информационная система поддержки решений
выбора направления обучения в университете
"""


def run_survey():
    """Главная функция опроса и рекомендации"""

    print("\n" + "=" * 50)
    print("   ПОМОЩНИК ВЫБОРА НАПРАВЛЕНИЯ ОБУЧЕНИЯ")
    print("=" * 50)

    # ===== БЛОК 1: Предпочтения =====
    print("\n📚 Оцените свой интерес к областям (1-5):")

    tech = int(input("   Технические науки (IT, инженерия): "))
    human = int(input("   Гуманитарные науки (языки, право): "))
    nature = int(input("   Естественные науки (биология, химия): "))

    # ===== БЛОК 2: Финансы =====
    print("\n💰 Ваши финансовые возможности:")
    print("   1 - только бюджет | 2 - бюджет+платное до 100т | 3 - без ограничений")
    money = int(input("   Ваш вариант (1-3): "))

    # ===== БЛОК 3: География =====
    print("\n🌍 Готовность к переезду:")
    print("   1 - только свой город | 2 - любой город России | 3 - готов за границу")
    geo = int(input("   Ваш вариант (1-3): "))

    # ===== АНАЛИЗ =====
    print("\n" + "=" * 50)
    print("🎯 ВАШИ РЕКОМЕНДАЦИИ:")
    print("=" * 50)

    # Определяем главный интерес
    scores = {"Технические": tech, "Гуманитарные": human, "Естественные": nature}
    main_interest = max(scores, key=scores.get)
    print(f"\n✓ Ваш основной интерес: {main_interest} науки")

    # Рекомендации по направлениям
    recommendations = []

    # Технические направления
    if tech >= 4:
        if money >= 1:
            recommendations.append("📱 Программная инженерия / Разработка ПО")
        if money >= 2 and geo >= 2:
            recommendations.append("🤖 Робототехника и мехатроника")

    # Гуманитарные направления
    if human >= 4:
        if money >= 1:
            recommendations.append("📖 Лингвистика / Переводческое дело")
        if geo >= 2:
            recommendations.append("⚖️ Юриспруденция")

    # Естественнонаучные направления
    if nature >= 4:
        if money >= 2:
            recommendations.append("🧬 Биотехнология")
        if money >= 1 and geo >= 2:
            recommendations.append("🏥 Медицина")

    # Добавляем базовые варианты (если список пуст)
    if not recommendations:
        recommendations.append("📚 Прикладная математика (широкий профиль)")
        recommendations.append("📚 Менеджмент / Управление проектами")

    # Вывод рекомендаций
    print("\n🏆 Вам могут подойти:")
    for i, rec in enumerate(recommendations[:4], 1):
        print(f"   {i}. {rec}")

    # ===== ФИНАЛЬНЫЙ СОВЕТ =====
    print("\n" + "=" * 50)
    print("💡 ВАЖНЫЙ СОВЕТ:")

    if money == 1:
        print("   • Упор на высокие баллы ЕГЭ (бюджетные места)")
    elif money == 2:
        print("   • Рассмотрите программы с оплатой по семестрам")
    else:
        print("   • Обратите внимание на частные вузы и зарубежные программы")

    if geo == 1:
        print("   • Изучите вузы в вашем городе")
    elif geo == 2:
        print("   • Москва, СПб, Казань, Новосибирск — топовые варианты")
    else:
        print("   • Подготовьте IELTS/TOEFL и зарубежные документы")

    print("=" * 50)

    # ===== ОТЧЕТ =====
    print("\n📋 КРАТКИЙ ОТЧЕТ:")
    print(f"   • Интересы: техника={tech}, гуманитарные={human}, естественные={nature}")
    print(f"   • Финансы: {money}/3")
    print(f"   • География: {geo}/3")
    print("\n✅ Спасибо за использование! Удачи с выбором!")


def main():
    """Запуск программы"""
    print("""
    ╔══════════════════════════════════════════════╗
    ║    СИСТЕМА ВЫБОРА НАПРАВЛЕНИЯ ОБУЧЕНИЯ      ║
    ║              (Упрощенная версия)             ║
    ╚══════════════════════════════════════════════╝
    """)

    while True:
        run_survey()

        # Спросить, хочет ли пользователь продолжить
        again = input("\n🔁 Пройти опрос заново? (да/нет): ").lower()
        if again not in ['да', 'yes', 'д', 'y']:
            print("\n👋 До свидания!")
            break


if __name__ == "__main__":
    main()